// Retorna uma frase diferente a cada 10 minutos
export function getQuote(storageKey) {
  const now = Date.now()
  const slot = Math.floor(now / (10 * 60 * 1000)) // 10 minutos em ms
  const key = `${storageKey}-${slot}`
  const stored = localStorage.getItem(key)
  if (stored) return JSON.parse(stored)
  const idx = Math.abs(hash(storageKey + slot)) % quotes.length
  const quote = quotes[idx]
  localStorage.setItem(key, JSON.stringify(quote))
  return quote
}

function hash(str) {
  let h = 0
  for (let i = 0; i < str.length; i++) {
    h = ((h << 5) - h) + str.charCodeAt(i)
    h |= 0
  }
  return h
}
